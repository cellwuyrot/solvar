import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "../..");
const read = (path) => readFileSync(resolve(root, path), "utf8");
test("SOLVAR requested storefront/admin changes are wired in source", () => {
  const shop = read("packages/web/src/shared/shop.ts");
  const catalog = read("packages/web/src/shared/catalog-display.ts");
  const admin = read("packages/web/src/web/pages/admin.tsx");
  const header = read("packages/web/src/web/components/header.tsx");
  const footer = read("packages/web/src/web/components/footer-3d.tsx");
  const info = read("packages/web/src/web/pages/information.tsx");
  const orders = read("packages/web/src/web/components/admin-orders.tsx");
  const styles = read("packages/web/src/web/styles.css");
  const schema = read("packages/web/src/api/database/schema.ts");
  const migration = read("packages/web/migrations/006_order_numbers.sql");
  assert.match(shop, /"cigarettes"/);
  assert.match(catalog, /cigarettes:\s*\{/);
  assert.match(styles, /\.category-grid \{ display: grid; grid-template-columns: repeat\(5,/);
  assert.match(admin, /\["orders", "Заказы клиентов", ClipboardList\]/);
  assert.match(orders, /order\.orderNumber/);
  assert.match(schema, /orderNumber: integer\("order_number"\)/);
  assert.match(migration, /ROW_NUMBER\(\) OVER/);
  assert.match(shop, /Информация по оплате предоставляется менеджером/);
  assert.match(footer, /zakaz@solvar\.su/);
  assert.doesNotMatch(footer, /settings\?\.vk|settings\?\.avito|Управление магазином/);
  assert.doesNotMatch(header, /Вход администратора|href="\/admin"/);
  assert.doesNotMatch(info, /href="\/admin">Управление/);
});
